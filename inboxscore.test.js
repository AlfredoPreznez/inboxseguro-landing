const assert = require('assert');
const s = require('./inboxscore.js');
assert.strictEqual(s.scoreSpf(['v=spf1 include:_spf.google.com ~all'], true).points, 22);
assert.strictEqual(s.scoreSpf(['v=spf1 -all'], true).points, 25);
assert.strictEqual(s.scoreSpf(['v=spf1 +all'], true).points, 0);
assert.strictEqual(s.scoreSpf(['v=spf1 a ~all', 'v=spf1 mx -all'], true).points, 5);
assert.strictEqual(s.scoreSpf([], true).points, 0);
assert.strictEqual(s.scoreSpf([], false).points, null);
assert.strictEqual(s.scoreDmarc(['v=DMARC1; p=reject; rua=mailto:a@b.c'], true).points, 35);
assert.strictEqual(s.scoreDmarc(['v=DMARC1; p=none'], true).points, 10);
assert.strictEqual(s.scoreDmarc(['v=DMARC1; p=quarantine; pct=50; rua=mailto:x@y.z'], true).points, 25);
assert.strictEqual(s.scoreDmarc([], true).points, 0);
assert.strictEqual(s.scoreDkim({ found: false }, true).points, 5);
assert.strictEqual(s.scoreDkim({ found: true, selector: 'google' }, true).points, 20);
const lists = [{ name: 'A' }, { name: 'B' }];
assert.strictEqual(s.scoreRbl({ lists, rows: [{ ip: '1.2.3.4', results: [{ status: 'clean' }, { status: 'listed' }] }] }, true).points, 10);
assert.strictEqual(s.scoreRbl({ lists, rows: [] }, true).points, null);
assert.deepStrictEqual(s.total([{ points: 20, max: 25 }, { points: null, max: 20 }, { points: 35, max: 35 }, { points: 20, max: 20 }]).score, 94);
assert.strictEqual(s.normalizeDomain('https://www.Ejemplo.com/x'), 'ejemplo.com');
assert.strictEqual(s.normalizeDomain('ana@ejemplo.cl'), 'ejemplo.cl');
assert.strictEqual(s.normalizeDomain('bad domain'), '');
console.log('inboxscore tests ok');
